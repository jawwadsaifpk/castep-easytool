# -*- coding: utf-8 -*-
"""
Cut-off energy and k-point convergence tests for CASTEP:
generate the series of inputs, then analyse the finished ``.castep`` files.
"""
import re
from pathlib import Path

import numpy as np

_NUM = r'[-+]?\d*\.?\d+(?:[EeDd][-+]?\d+)?'

DEFAULT_VALUES = {
    "cutoff": [300, 400, 500, 600, 700, 800],       # eV
    "kpoints": [0.10, 0.08, 0.06, 0.05, 0.04, 0.03],  # MP spacing, 1/A
}


def parse_values(spec, kind):
    """'300,400,500' -> [300.0, 400.0, 500.0]; None -> defaults for ``kind``."""
    if not spec:
        return [float(v) for v in DEFAULT_VALUES[kind]]
    try:
        vals = [float(v) for v in spec.replace(";", ",").split(",") if v.strip()]
    except ValueError:
        raise ValueError(f"cannot parse --values '{spec}': use a comma-separated list such as 300,400,500")
    if len(vals) < 2:
        raise ValueError("a convergence test needs at least two values")
    return vals


def _tag(kind, v):
    return f"ecut_{int(round(v)):04d}" if kind == "cutoff" else f"kspc_{v:.3f}"


def write_series(kind, stem, cell_body, values, out_dir, task="SinglePoint", xc=None,
                 fixed_cutoff=600.0, fixed_kspacing=0.05, spin=False):
    """Write <out_dir>/<stem>_<tag>.cell/.param and run_all.sh. Returns the list of seeds."""
    out_dir.mkdir(parents=True, exist_ok=True)
    seeds = []
    for v in values:
        seed = f"{stem}_{_tag(kind, v)}"
        ecut = v if kind == "cutoff" else fixed_cutoff
        ksp = v if kind == "kpoints" else fixed_kspacing
        (out_dir / f"{seed}.cell").write_text(
            f"# {kind} convergence test generated by castep-easytool\n\n{cell_body}\n"
            f"KPOINTS_MP_SPACING : {ksp:g}\n", encoding="utf-8")
        params = {"TASK": task, "CUT_OFF_ENERGY": f"{ecut:g}"}
        if xc:
            params["XC_FUNCTIONAL"] = xc
        if spin:
            params["SPIN_POLARIZED"] = "true"
        if kind == "cutoff":
            # Without this CASTEP applies a finite-basis correction that hides the cutoff error.
            params["FINITE_BASIS_CORR"] = "0"
        width = max(len(k) for k in params)
        (out_dir / f"{seed}.param").write_text(
            "".join(f"{k:<{width}} : {p}\n" for k, p in params.items()), encoding="utf-8")
        seeds.append(seed)
    script = ["#!/bin/bash",
              "# Run every test; override with e.g.  NP=16 CASTEP=castep.mpi ./run_all.sh",
              'NP=${NP:-4}', 'CASTEP=${CASTEP:-castep.mpi}', 'cd "$(dirname "$0")"',
              "for seed in " + " ".join(seeds) + "; do",
              '  mpirun -np "$NP" "$CASTEP" "$seed"', "done", ""]
    (out_dir / "run_all.sh").write_text("\n".join(script), encoding="utf-8", newline="\n")
    return seeds


def read_result(path):
    """Extract cutoff, k-grid, atom count and final energy from one finished .castep file."""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    start = text.rfind("Run started")
    seg = text[start:] if start >= 0 else text

    def last(pattern, src):
        m = list(re.finditer(pattern, src, re.MULTILINE))
        return m[-1] if m else None

    e = last(rf'Final free energy \(E-TS\)\s*=\s*({_NUM})\s*eV', text) \
        or last(rf'Final energy, E\s*=\s*({_NUM})\s*eV', text)
    n = last(r'Total number of ions in cell\s*=\s*(\d+)', seg)
    c = last(rf'plane wave basis set cut-off\s*:\s*({_NUM})\s*eV', seg)
    k = last(r'MP grid size for SCF calculation is\s+(\d+)\s+(\d+)\s+(\d+)', seg)
    nk = last(r'Number of kpoints used\s*=\s*(\d+)', seg)
    if not (e and n and c):
        raise ValueError("final energy / atom count / cut-off not found (calculation unfinished?)")
    return {
        "file": Path(path).name,
        "cutoff": float(c.group(1)),
        "kgrid": tuple(int(x) for x in k.groups()) if k else None,
        "n_kpoints": int(nk.group(1)) if nk else None,
        "n_atoms": int(n.group(1)),
        "energy": float(e.group(1).replace("D", "E")),
        "finished": "Total time" in text,
    }


def collect(paths):
    """Read all result files; returns (results, skipped[(name, reason)])."""
    results, skipped = [], []
    for p in paths:
        try:
            results.append(read_result(p))
        except (ValueError, OSError) as ex:
            skipped.append((Path(p).name, str(ex)))
    return results, skipped


def analyse(kind, results, tol_meV=1.0):
    """
    Sort results by the tested parameter and compute the energy error relative to
    the most converged point. Returns (rows, recommended_label) where rows are dicts.
    """
    if kind == "cutoff":
        key = lambda r: r["cutoff"]
        label = lambda r: f"{r['cutoff']:g} eV"
        xval = lambda r: r["cutoff"]
    else:
        # More k-points = more converged. Order by full-grid size.
        gp = lambda r: int(np.prod(r["kgrid"])) if r["kgrid"] else (r["n_kpoints"] or 0)
        key = gp
        label = lambda r: ("x".join(map(str, r["kgrid"])) if r["kgrid"] else f"{r['n_kpoints']} kpts")
        xval = gp
    rs = sorted(results, key=key)
    ref = rs[-1]
    rows = []
    for r in rs:
        e_atom = r["energy"] / r["n_atoms"]
        rows.append({"label": label(r), "x": xval(r), "e_atom": e_atom,
                     "err_meV": (e_atom - ref["energy"] / ref["n_atoms"]) * 1000.0,
                     "n_kpoints": r["n_kpoints"], "file": r["file"]})
    # Smallest setting from which every larger one stays within tol.
    rec = None
    for i in range(len(rows) - 1):
        if all(abs(x["err_meV"]) <= tol_meV for x in rows[i:]):
            rec = rows[i]["label"]
            break
    return rows, rec


def report_lines(kind, rows, rec, tol_meV, skipped=()):
    name = "Cut-off energy" if kind == "cutoff" else "k-point grid"
    out = [f"{name} convergence test  (tolerance {tol_meV:g} meV/atom, reference = last row)", "",
           f"{'Setting':<12} {'k-pts':>6} {'E/atom (eV)':>16} {'dE vs ref (meV/atom)':>22}  File"]
    for r in rows:
        out.append(f"{r['label']:<12} {str(r['n_kpoints'] or '-'):>6} {r['e_atom']:>16.6f} "
                   f"{r['err_meV']:>22.3f}  {r['file']}")
    out.append("")
    if rec:
        out.append(f"Converged to {tol_meV:g} meV/atom from: {rec}")
    else:
        out.append(f"NOT converged to {tol_meV:g} meV/atom within the tested range - extend the series.")
    if len(rows) > 1 and abs(rows[-1]["err_meV"]) == 0 and abs(rows[-2]["err_meV"]) > tol_meV:
        out.append("Note: the reference point is the highest setting, so a large error at the second-highest "
                   "point means the energy is still changing.")
    for name_, why in skipped:
        out.append(f"Skipped {name_}: {why}")
    return out


def plot(kind, rows, tol_meV=1.0, title=None):
    import matplotlib.pyplot as plt
    from matplotlib.ticker import MaxNLocator

    xs = np.arange(len(rows)) if kind == "kpoints" else np.array([r["x"] for r in rows])
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.2))
    e = np.array([r["e_atom"] for r in rows])
    a1.plot(xs, e, "o-", color="tab:blue")
    a1.ticklabel_format(useOffset=False, style="plain", axis="y")
    a1.set_ylabel("Total energy per atom (eV)")
    err = np.abs([r["err_meV"] for r in rows])
    ok = err <= tol_meV
    nz = err > 0  # the reference point is exactly 0 by construction: not drawn on a log axis
    a2.plot(xs[nz], err[nz], "-", color="gray", lw=1)
    a2.scatter(xs[nz & ok], err[nz & ok], color="tab:green", zorder=3, label="within tol")
    a2.scatter(xs[nz & ~ok], err[nz & ~ok], facecolors="white", edgecolors="tab:red", zorder=3,
               label="outside tol")
    a2.annotate("last point = reference", xy=(0.03, 0.04), xycoords="axes fraction", fontsize=8, color="gray")
    a2.axhline(tol_meV, color="k", ls="--", lw=1, label=f"tol = {tol_meV:g} meV/atom")
    a2.set_yscale("log")
    a2.set_ylabel("|E - E(ref)| (meV/atom)")
    a2.legend(fontsize=8)
    for ax in (a1, a2):
        ax.grid(alpha=0.3)
        if kind == "kpoints":
            ax.set_xticks(xs)
            ax.set_xticklabels([r["label"] for r in rows], rotation=30, ha="right")
            ax.set_xlabel("k-point grid")
        else:
            ax.set_xlabel("Cut-off energy (eV)")
            ax.xaxis.set_major_locator(MaxNLocator(integer=True))
    fig.suptitle(title or ("Cut-off energy convergence" if kind == "cutoff" else "k-point convergence"))
    fig.tight_layout()
    return fig
