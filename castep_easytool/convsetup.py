# -*- coding: utf-8 -*-
"""
Turn a .cif or .cell file into a ready-to-run convergence set-up:
primitive-cell check/conversion, <seed>.cell/.param, and a tailored <seed>.conv.
"""
import json
import shutil
from pathlib import Path

from . import autoconv as ac
from . import cellio, kmesh

_PLACEHOLDER_ECUT = 600


# ---------------------------------------------------------------------------
# Remembered CASTEP command
# ---------------------------------------------------------------------------

def settings_path():
    return Path.home() / ".castep-easytool.json"


def load_saved_command():
    try:
        return json.loads(settings_path().read_text(encoding="utf-8")).get("castep_command")
    except (OSError, ValueError):
        return None


def save_command(cmd):
    try:
        data = {}
        if settings_path().exists():
            data = json.loads(settings_path().read_text(encoding="utf-8"))
        data["castep_command"] = cmd
        settings_path().write_text(json.dumps(data, indent=2), encoding="utf-8")
        return True
    except (OSError, ValueError):
        return False


def command_executable(cmd):
    """(first token, found on PATH?) for a castep_command."""
    try:
        first = ac.split_command(cmd, "seed")[0]
    except ValueError:
        return cmd, False
    return first, shutil.which(first) is not None


# ---------------------------------------------------------------------------
# Set-up
# ---------------------------------------------------------------------------

def _param_text(xc, spin):
    lines = ["# CASTEP .param generated by castep-easytool for convergence tests",
             "# (cut_off_energy is a placeholder: every convergence job sets its own)",
             "task              : GeometryOptimization",
             f"xc_functional     : {xc}",
             f"cut_off_energy    : {_PLACEHOLDER_ECUT} eV"]
    if spin:
        lines.append("spin_polarized    : true")
    return "\n".join(lines) + "\n"


def _is_spin_param(text):
    import re
    return bool(re.search(r"^\s*spin_polarized?\s*[:=]\s*(true|t|yes|1)\b", text, re.IGNORECASE | re.MULTILINE))


def prepare(input_path, out_dir=None, xc="PBE", spin=False, cmd=None, primitive=None,
            threshold=1.0, log=print):
    """
    Build the convergence folder for ``input_path`` (.cif or .cell).

    primitive: None = automatic (.cif: convert; .cell: warn only), True = convert,
    False = never convert. Returns a dict with ``messages`` [(level, text)], ``seed``,
    ``out_dir``, ``conv_path``, ``cfg`` and conversion details. Existing files in the
    output folder are never overwritten.
    """
    input_path = Path(input_path)
    suffix = input_path.suffix.lower()
    msgs = []

    def info(t):
        msgs.append(("info", t))

    def warn(t):
        msgs.append(("warn", t))

    if suffix not in (".cif", ".cell"):
        raise ValueError(f"unsupported input '{input_path.name}': use a .cif, .cell or .conv file")
    if not input_path.exists():
        raise FileNotFoundError(f"File not found: '{input_path}'")

    seed = input_path.stem
    out = Path(out_dir) if out_dir else input_path.resolve().parent / f"{seed}_convergence"

    src_param_text, cell_info, cell_text_in = None, None, None
    if suffix == ".cif":
        from pymatgen.core.structure import Structure
        struct = Structure.from_file(str(input_path))
        if not struct.is_ordered:
            raise ValueError("the structure has disordered (partially occupied) sites, which CASTEP "
                             "cannot represent; supply an ordered structure")
    else:
        cell_text_in = input_path.read_text(encoding="utf-8", errors="replace")
        cell_info = cellio.read_cell(cell_text_in)
        struct = cellio.to_structure(cell_info)
        pp = input_path.with_suffix(".param")
        if pp.exists():
            src_param_text = pp.read_text(encoding="utf-8", errors="replace")
            info(f"Using the existing '{pp.name}' for the calculation settings.")
            if xc != "PBE" or spin:
                warn("--xc/--spin are ignored because a .param file already exists; edit it instead.")
    is_spin = spin or (src_param_text is not None and _is_spin_param(src_param_text))

    # ---- primitive-cell check ------------------------------------------------
    prim, sg = cellio.primitive_of(struct)
    n0 = len(struct)
    convert = False
    if prim is None:
        info(f"The structure is already a primitive cell: {n0} atoms, space group {sg}.")
    else:
        desc = (f"{n0} atoms -> {len(prim)} atoms in the primitive cell; space group {sg}; "
                f"volume {struct.volume:.2f} -> {prim.volume:.2f} A^3")
        if primitive is False:
            warn(f"The structure is NOT primitive ({desc}). Keeping it as given (--no-primitive); "
                 f"the convergence jobs will be about {n0 / len(prim):.0f}x more expensive.")
        elif is_spin and primitive is not True:
            warn(f"The structure is not primitive ({desc}), but the calculation is spin-polarised: "
                 "a primitive cell can destroy an antiferromagnetic or other ordered-spin arrangement, "
                 "so it was NOT converted. Use --primitive to convert anyway.")
        elif suffix == ".cell" and primitive is not True:
            warn(f"The structure is not primitive ({desc}). A .cell file is not converted automatically "
                 "because it may hold blocks that cannot be carried over; use --primitive to convert "
                 "(species-level blocks are kept, the rest is listed). Continuing with the cell as given.")
        else:
            convert = True
            info(f"Converted to the primitive cell: {desc}. Your input file is untouched; the primitive "
                 f"cell is used for ALL calculations (its lattice vectors differ from the input).")

    used = prim if convert else struct
    n_atoms = len(used)

    # ---- write inputs ----------------------------------------------------------
    out.mkdir(parents=True, exist_ok=True)
    cell_out, param_out, conv_out = out / f"{seed}.cell", out / f"{seed}.param", out / f"{seed}.conv"
    existing = [p.name for p in (cell_out, param_out, conv_out) if p.exists()]
    if existing:
        warn(f"Kept existing file(s) in '{out}': {', '.join(existing)} (not overwritten; delete them or "
             "use --out to start fresh).")

    header = f"# CASTEP .cell generated by castep-easytool from '{input_path.name}'"
    if not cell_out.exists():
        if suffix == ".cell" and convert:
            text, kept, dropped, spin_tags = cellio.convert_cell_to_primitive(cell_info, used)
            cell_out.write_text(text, encoding="utf-8")
            if kept:
                info(f"Carried over species-level blocks: {', '.join(kept)}.")
            if dropped:
                warn(f"Dropped blocks that depend on the old atom list: {', '.join(dropped)}. Re-create "
                     "them for the primitive cell if you need them.")
            if spin_tags:
                warn("Per-atom spin tags in the old POSITIONS block were not transferred.")
        elif suffix == ".cell":
            cell_out.write_text(cell_text_in, encoding="utf-8")
        else:
            cell_out.write_text(cellio.cell_text(used, header=header), encoding="utf-8")
    if convert and suffix == ".cif":
        from pymatgen.io.cif import CifWriter
        prim_cif = out / f"{seed}_primitive.cif"
        if not prim_cif.exists():
            CifWriter(used).write_file(str(prim_cif))
            info(f"Primitive cell saved as '{prim_cif.name}'.")
    if not param_out.exists():
        param_out.write_text(src_param_text if src_param_text is not None else _param_text(xc, spin),
                             encoding="utf-8")
        if src_param_text is None:
            info(f"Wrote '{param_out.name}' (task GeometryOptimization, {xc}"
                 f"{', spin-polarised' if spin else ''}); edit it before the production run if needed.")

    # ---- config ----------------------------------------------------------------
    chosen = cmd or load_saved_command() or ac.DEFAULTS["castep_command"]
    cfg = ac.default_config(seed)
    cfg.update(castep_command=chosen, n_atoms=n_atoms, threshold_mev=threshold)
    notes = {}
    exe, found = command_executable(chosen)
    if not found:
        warn(f"'{exe}' was not found on PATH, so CASTEP cannot be started from here "
             "(edit castep_command in the .conv or pass --cmd).")

    cell_for_k = cellio.read_cell(cell_out.read_text(encoding="utf-8", errors="replace"))
    lat = cell_for_k["lattice"]
    notes["kpn_max"] = (f"Lattice-aware range for this cell: N = 1..{kmesh.auto_n_max(lat, cfg['kspacing_min'])} "
                        f"(|b|/2pi = " + ", ".join(f"{x:.4f}" for x in kmesh.recip_lengths(lat)) + " 1/A).")

    notes["ecut_start"] = "Default range: the cut-off scan finds the converged value."
    info(f"Cut-off scan range: {cfg['ecut_start']}-{cfg['ecut_max']} eV.")
    ecut_source = "default"

    if not conv_out.exists():
        conv_out.write_text(ac.render_conv(cfg, notes), encoding="utf-8")
    else:
        cfg, _ = ac.parse_config(conv_out)  # honour the file the user already has
    return {"seed": seed, "out_dir": out, "conv_path": conv_out, "cfg": cfg, "messages": msgs,
            "converted": convert, "n_atoms": n_atoms, "ecut_source": ecut_source}
